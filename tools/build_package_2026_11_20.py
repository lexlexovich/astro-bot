def horoscope(s: dict, idx: int) -> dict:
    moon=s["moon"]; aspect=s["aspects"][0] if s["aspects"] else None
    actions=["сначала уточните задачу","закройте один старый хвост","оставьте место для паузы","говорите короче и точнее","не обещайте за будущего себя","проверьте детали перед стартом"]
    out={}
    for j,sign in enumerate(SIGNS):
        if sign==moon["sign_ru"]: text=f"Луна у вас: эмоции заметнее. {actions[(idx+j)%6].capitalize()}."
        elif aspect and sign in (aspect["a"],aspect["b"]): text=f"Небо подчёркивает ваш знак. {actions[(idx+j)%6].capitalize()}."
        else: text=f"Луна в {moon['sign_ru_in']}: {actions[(idx+j)%6]}. Без лишней драмы."
        out[sign]=text[:95]
    return out

